-- ============================================================
-- 升级脚本：文件上传记录菜单更名（图片管理扩展为文件管理，可管理图片/语音/视频）
-- 影响表：t_menus（menu_id=20 的 file_uploads 菜单名）
-- 执行方式：数据库控制台（DMS）或 mysql 客户端执行
-- 幂等性：是（按 menu_id 更新，可重复执行）
-- 说明：file_uploads 模块现同时登记图片/语音/视频（biz=voice/videos），
--       后台"文件上传记录"支持按业务类型筛选，视频有播放预览与压缩比展示。
-- ============================================================
UPDATE `t_menus` SET `menu_name` = '文件上传记录'
WHERE `menu_id` = 20 AND `menu_url` = '/module/file_uploads' AND `menu_name` = '图片上传记录';
